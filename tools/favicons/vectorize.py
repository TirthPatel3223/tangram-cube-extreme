"""
Favicon renderer, step 2 of 2: trace the colour-index images from `render.gen.ts` into SVG.

For every colour, the mask is smoothed slightly, upsampled (so contours land between pixels), traced
with OpenCV (holes included) and simplified. The face is a black rounded square; each sticker
colour is painted on top of it. Coordinates are on a 64 x 64 viewBox.

Usage: python -I tools/favicons/vectorize.py <render dir> <svg dir> [<preview dir>]
"""

import json
import sys
from pathlib import Path

import cv2
import numpy as np

VIEW = 64.0
UP = 4  # upsampling before tracing
MARGIN = 1.0  # viewBox units between the face edge and the icon edge
CORNER = 2.0  # rounding of the black face square (the cube's bevelled corners, a little exaggerated)
BLACKS = ("#141416", "#0b0b0d")


def trace(mask: np.ndarray, size: int, extent: float, eps: float, min_area: float) -> str:
    """SVG path data (even-odd) for a boolean mask."""
    # Drop slivers thinner than about 0.4 viewBox units (stickers seen edge-on near the face's border
    # or inside a hollow corner): invisible at favicon size, but they'd still cost path data.
    k = max(3, (size // 160) | 1)
    mask = cv2.morphologyEx(mask.astype(np.uint8), cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k)))
    m = cv2.GaussianBlur(mask.astype(np.float32), (0, 0), 0.8)
    m = cv2.resize(m, (size * UP, size * UP), interpolation=cv2.INTER_LINEAR)
    binary = (m >= 0.5).astype(np.uint8)
    contours, _ = cv2.findContours(binary, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    # Pixel centre -> model units -> viewBox: the face [-1, 1] spans [MARGIN, VIEW - MARGIN].
    k = (VIEW / 2 - MARGIN)
    to_view = lambda v: VIEW / 2 + k * (((v + 0.5) / (size * UP)) * 2 * extent - extent)
    parts = []
    for c in contours:
        if cv2.contourArea(c) * (k * 2 * extent / (size * UP)) ** 2 < min_area:
            continue
        a = cv2.approxPolyDP(c, eps * UP, True).reshape(-1, 2).astype(np.float64)
        if len(a) < 3:
            continue
        pts = [(to_view(x), to_view(y)) for x, y in a]
        parts.append("M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + "Z")
    return "".join(parts)


def load(idx_path: Path, meta: dict) -> np.ndarray:
    """The colour-index image (0 = outside the face)."""
    size = meta["size"]
    return np.fromfile(idx_path, dtype=np.uint8).reshape(size, size)


def vectorize(idx_path: Path, meta: dict, out_svg: Path, title: str) -> list[tuple[str, str]]:
    size = meta["size"]
    extent = meta["extent"]
    palette = meta["palette"]
    img = load(idx_path, meta)
    layers = []
    # The stickers, painted over the black face (the renderer already turned every gap, the core
    # and the bare edge bands into body black).
    for ci, colour in enumerate(palette):
        if ci == 0 or colour in BLACKS:
            continue
        d = trace(img == ci, size, extent, 0.35, 0.25)
        if d:
            layers.append((colour, d))
    side = VIEW - 2 * MARGIN
    face = f'  <rect x="{MARGIN:g}" y="{MARGIN:g}" width="{side:g}" height="{side:g}" rx="{CORNER:g}" fill="{BLACKS[0]}"/>'
    paths = "\n".join([face] + [f'  <path fill="{c}" fill-rule="evenodd" d="{d}"/>' for c, d in layers])
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEW:g} {VIEW:g}">\n'
        f"  <title>{title}</title>\n"
        f"  <!-- Generated by tools/favicons (render.gen.ts + vectorize.py): {meta['note']} -->\n"
        f"{paths}\n</svg>\n"
    )
    out_svg.write_text(svg, encoding="utf-8")
    return layers


TITLES = {
    "tangram-cube-extreme": "Tangram Cube Extreme",
    "tangram-cube": "Tangram Cube",
    "curvy-copter": "Curvy Copter",
    "curvy-copter-plus": "Curvy Copter Plus",
    "maltese-gear-cube": "Maltese Gear Cube",
}


def preview(idx_path: Path, meta: dict, out_png: Path) -> None:
    size = meta["size"]
    img = load(idx_path, meta)
    lut = np.zeros((256, 3), np.uint8)
    lut[0] = (255, 255, 255)
    for i, c in enumerate(meta["palette"][1:], 1):
        lut[i] = (int(c[5:7], 16), int(c[3:5], 16), int(c[1:3], 16))
    cv2.imwrite(str(out_png), lut[img])


def main() -> None:
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    prev = Path(sys.argv[3]) if len(sys.argv) > 3 else None
    dst.mkdir(parents=True, exist_ok=True)
    for meta_path in sorted(src.glob("*.json")):
        name = meta_path.stem
        meta = json.loads(meta_path.read_text())
        layers = vectorize(src / f"{name}.idx", meta, dst / f"{name}.svg", TITLES.get(name, name))
        if prev:
            prev.mkdir(parents=True, exist_ok=True)
            preview(src / f"{name}.idx", meta, prev / f"{name}-raster.png")
        size = (dst / f"{name}.svg").stat().st_size
        print(f"{name}: {len(layers)} layers, {size / 1024:.1f} KiB ({meta['note']})")


if __name__ == "__main__":
    main()
