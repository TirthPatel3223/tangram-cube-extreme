import { type P2, type PathNode, SketchError, add2, mul2, path, sub2 } from './sketch';

/**
 * Sticker outlines of the Maltese Gear Cube.
 *
 * - The star is a constrained parametric sketch: straight lines and tangent circular arcs,
 *   mirror-symmetric by construction, with sharp corners only at its four points. Its numbers were
 *   fitted to a top-down photo by `tools/maltese/fit_stickers.py` (rectified on a 2 mm grid, all four
 *   stars averaged, forward-model least squares); the same construction lives in the fitter (Python),
 *   so keep the two in step.
 * - The gear is traced from the user's drawing of it by `tools/maltese/trace_gear.py` (mirror-averaged,
 *   smoothed, sized on the same photo), with its hub on the spin axis.
 *
 * The scale comes from the gear hub: tan 22.5° × 30 mm = 12.43 mm from the face centre. See
 * docs/maltese-gear-cube.md.
 */

