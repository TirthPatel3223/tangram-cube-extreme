/** Model units per mm (the face plane is 1 = 30 mm from the centre). */
const U = 1 / 30;

/**
 * The corner star on the F face of the UFR corner, in face coordinates (x right, y up, face centre at
 * the origin), model units, counterclockwise.
 *
 * One half is sketched and mirrored about x = y: the inner arm (pointing down at the gear Fr, centre
 * line x = hc, sharp tip at y = t, half-width wi at its root) and the outer arm (y from yl to yu) which
 * runs to x = ue and ends in a fin flaring down towards the edge midpoint: a straight inner edge leaving
 * the arm at x = bx (fillet r4) to the sharp tip (fx, fy), and a straight outer edge back up to (ue, ye).
 * Fillets: r1 between the two inner arms (on the diagonal), r2 at the inner arm's root, r3 between the
 * two outer arms (on the diagonal), re at the arm's end.
 */
export function starSticker(mm: typeof STAR_MM = STAR_MM): P2[] {
  const s = Object.fromEntries(Object.entries(mm).map(([k, v]) => [k, v * U])) as Record<keyof typeof STAR_MM, number>;
  const ti: P2 = [s.hc, s.t];
  const qdl: P2 = [s.hc - s.wi, s.yl];
  const d = sub2(qdl, ti);
  if (Math.abs(d[0] - d[1]) < 1e-12) throw new SketchError('inner arm side parallel to the diagonal');
  const k = (ti[1] - ti[0]) / (d[0] - d[1]);
  const nn = add2(ti, mul2(d, k)); // inner notch corner, on the diagonal
  const half: PathNode[] = [
    { p: nn, r: s.r1 },
    { p: ti, r: 0 },
    { p: [s.hc + s.wi, s.yl], r: s.r2 },
    { p: [s.bx, s.yl], r: s.r4 },
    { p: [s.fx, s.fy], r: 0 },
    { p: [s.ue, s.ye], r: s.re },
    { p: [s.ue, s.yu], r: s.re },
    { p: [s.yu, s.yu], r: s.r3 }, // outer notch corner, on the diagonal
  ];
  const mirrored = half
    .slice(1, 7)
    .reverse()
    .map((nd): PathNode => ({ p: [nd.p[1], nd.p[0]], r: nd.r }));
  return path([...half, ...mirrored]);
}

